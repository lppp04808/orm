<?php

declare(strict_types=1);

namespace Tests\Pixiaoka\Orm;

use PDO;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Pixiaoka\Orm\Annotation\Column;
use Pixiaoka\Orm\Annotation\PrimaryKey;
use Pixiaoka\Orm\Entity;
use Pixiaoka\Orm\Gateway\Connection;
use Pixiaoka\Orm\Gateway\DriverAwareConnection;
use Pixiaoka\Orm\Gateway\EntityGateway;
use Pixiaoka\Orm\Gateway\PdoConnection;
use Pixiaoka\Orm\Session;

final class GeneratedOnlyInsertTest extends TestCase
{
    protected function setUp(): void
    {
        Session::discard();
    }

    protected function tearDown(): void
    {
        Session::discard();
        GeneratedOnlyRow::$liveTable = 'generated_only';
    }

    #[DataProvider('defaultValueDialects')]
    public function testSingleAndBatchDefaultValueSqlUsesValidDialect(string $driver, string $expected): void
    {
        $connection = new GeneratedOnlyDialectConnection($driver);
        Session::use(new EntityGateway($connection));

        $entity = new GeneratedOnlyRow();
        $entity->save();
        self::assertSame(7, $entity->id);
        $expectedSingle = $driver === 'mysql' ? $expected : 'INSERT INTO "' . GeneratedOnlyRow::table() . '" DEFAULT VALUES RETURNING "id"';
        self::assertSame($expectedSingle, $connection->queries[0] ?? $connection->executes[0]);

        GeneratedOnlyRow::insertAll([[], []]);
        $actual = $driver === 'mysql' ? array_slice($connection->executes, 1) : array_slice($connection->queries, 1);
        self::assertSame([$expectedSingle, $expectedSingle], $actual);
    }

    /** @return array<string, array{string, string}> */
    public static function defaultValueDialects(): array
    {
        return [
            'mysql' => ['mysql', 'INSERT INTO `generated_only` () VALUES ()'],
            'pgsql' => ['pgsql', 'DEFAULT VALUES'],
            'sqlite' => ['sqlite', 'DEFAULT VALUES'],
        ];
    }

    #[DataProvider('liveDrivers')]
    public function testRealDatabaseSingleAndBatchInserts(string $driver): void
    {
        $pdo = $this->connection($driver);
        $table = 'generated_only_' . bin2hex(random_bytes(5));
        GeneratedOnlyRow::$liveTable = $table;
        try {
            $q = $driver === 'mysql' ? '`' : '"';
            $generated = match ($driver) {
                'mysql' => 'BIGINT AUTO_INCREMENT PRIMARY KEY',
                'pgsql' => 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                default => 'INTEGER PRIMARY KEY AUTOINCREMENT',
            };
            $pdo->exec("CREATE TABLE $q$table$q (id $generated, body VARCHAR(100) NOT NULL DEFAULT 'default-body')");
            $reader = new \Pixiaoka\Orm\Metadata\MetadataReader();
            $reader->read(GeneratedOnlyRow::class);
            $gateway = new EntityGateway(new PdoConnection($pdo), $reader);
            Session::use($gateway);

            $first = new GeneratedOnlyRow();
            $first->save();
            self::assertSame(1, $first->id);
            GeneratedOnlyRow::insertAll([[], []]);
            self::assertSame(3, (int) $pdo->query("SELECT COUNT(*) FROM $q$table$q")->fetchColumn());

            $second = new GeneratedOnlyRow();
            $third = new GeneratedOnlyRow();
            GeneratedOnlyRow::insertAll([$second, $third]);
            self::assertSame([4, 5], [$second->id, $third->id]);
            self::assertSame(['default-body'], array_unique($pdo->query("SELECT body FROM $q$table$q")->fetchAll(PDO::FETCH_COLUMN)));
        } finally {
            Session::discard();
            GeneratedOnlyRow::$liveTable = 'generated_only';
            $pdo->exec("DROP TABLE IF EXISTS " . ($driver === 'mysql' ? '`' : '"') . $table . ($driver === 'mysql' ? '`' : '"'));
        }
    }

    public function testDefaultValueBatchRejectsInvalidRowsBeforeAnySql(): void
    {
        $connection = new GeneratedOnlyDialectConnection('sqlite');
        $gateway = new EntityGateway($connection);
        Session::use($gateway);
        $persisted = new GeneratedOnlyRow();
        $persisted->save();
        $before = count($connection->queries);

        foreach ([
            [['id' => 1]],
            [[0 => 'not-a-field']],
            [['unknown' => 'value']],
            [[new \stdClass()]],
            [[new GeneratedOnlyOtherRow()]],
            [[$persisted]],
        ] as $rows) {
            try {
                GeneratedOnlyRow::insertAll($rows);
                self::fail('Invalid default-value batch input must not be silently ignored');
            } catch (\InvalidArgumentException|\TypeError|\Pixiaoka\Orm\Exception\IdentityException) {
            }
            self::assertCount($before, $connection->queries);
        }
        $assigned = new GeneratedOnlyRow();
        $assigned->id = 42;
        try {
            GeneratedOnlyRow::insertAll([$assigned]);
            self::fail('A generated key must not be ignored merely because it is the only field');
        } catch (\InvalidArgumentException $e) {
            self::assertStringContainsString('generated', $e->getMessage());
        }
        self::assertCount($before, $connection->queries);
    }

    public function testDefaultValueBatchRejectsRepeatedEntityBeforeHooksAndSql(): void
    {
        $pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec('CREATE TABLE generated_only (id INTEGER PRIMARY KEY AUTOINCREMENT)');
        Session::use(new EntityGateway(new PdoConnection($pdo)));
        $row = new GeneratedOnlyHookRow();
        $row->failBeforeInsert = true;

        try {
            GeneratedOnlyHookRow::insertAll([$row, [], $row]);
            self::fail('同一实体不能对应批次内的两行默认值');
        } catch (\InvalidArgumentException $e) {
            self::assertStringContainsString('same entity instance', $e->getMessage());
        }

        self::assertSame(0, (int) $pdo->query('SELECT COUNT(*) FROM generated_only')->fetchColumn());
        self::assertTrue($row->isNew());
        self::assertFalse($row->hasGatewayBinding());
        self::assertFalse($row->propSet('id'));
    }

    public function testDefaultValueBatchBeforeHookFailureDoesNotBindOrWriteAnyEntity(): void
    {
        $pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec('CREATE TABLE generated_only (id INTEGER PRIMARY KEY AUTOINCREMENT)');
        $gateway = new EntityGateway(new PdoConnection($pdo));
        Session::use($gateway);
        $first = new GeneratedOnlyHookRow();
        $second = new GeneratedOnlyHookRow();
        $second->failBeforeInsert = true;

        try {
            GeneratedOnlyHookRow::insertAll([$first, $second]);
            self::fail('A before-hook failure must prevent the entire batch');
        } catch (\RuntimeException $e) {
            self::assertSame('injected before-insert failure', $e->getMessage());
        }

        self::assertSame(0, (int) $pdo->query('SELECT COUNT(*) FROM generated_only')->fetchColumn());
        foreach ([$first, $second] as $row) {
            self::assertTrue($row->isNew());
            self::assertFalse($row->propSet('id'));
            self::assertFalse($row->hasGatewayBinding());
            self::assertSame(0, $row->afterInserts);
        }
    }

    public function testDefaultValueBatchAfterHookFailureRollsBackRowsAndEntityState(): void
    {
        $pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec('CREATE TABLE generated_only (id INTEGER PRIMARY KEY AUTOINCREMENT)');
        $gateway = new EntityGateway(new PdoConnection($pdo));
        Session::use($gateway);
        $first = new GeneratedOnlyHookRow();
        $second = new GeneratedOnlyHookRow();
        $second->failAfterInsert = true;

        try {
            GeneratedOnlyHookRow::insertAll([$first, $second]);
            self::fail('An after-hook failure must propagate and roll back the batch');
        } catch (\RuntimeException $e) {
            self::assertSame('injected after-insert failure', $e->getMessage());
        }

        self::assertSame(0, (int) $pdo->query('SELECT COUNT(*) FROM generated_only')->fetchColumn());
        foreach ([$first, $second] as $row) {
            self::assertTrue($row->isNew());
            self::assertFalse($row->propSet('id'));
            self::assertSame([], $row->takeOriginalPrimary());
        }
        self::assertNull(GeneratedOnlyHookRow::find(['id' => 1]));
    }

    public function testDefaultValueBatchSqlFailureRollsBackEarlierRowsAndEntityState(): void
    {
        $pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec('CREATE TABLE generated_only (id INTEGER PRIMARY KEY AUTOINCREMENT)');
        $pdo->exec("CREATE TRIGGER fail_default_batch BEFORE INSERT ON generated_only WHEN (SELECT COUNT(*) FROM generated_only) = 2 BEGIN SELECT RAISE(ABORT, 'injected default batch failure'); END");
        $gateway = new EntityGateway(new PdoConnection($pdo));
        Session::use($gateway);
        $rows = [new GeneratedOnlyHookRow(), new GeneratedOnlyHookRow(), new GeneratedOnlyHookRow()];

        try {
            GeneratedOnlyHookRow::insertAll($rows);
            self::fail('The third row must exercise SQL rollback, not just hook validation');
        } catch (\PDOException $e) {
            self::assertStringContainsString('injected default batch failure', $e->getMessage());
        }

        self::assertSame(0, (int) $pdo->query('SELECT COUNT(*) FROM generated_only')->fetchColumn());
        foreach ($rows as $row) {
            self::assertTrue($row->isNew());
            self::assertFalse($row->propSet('id'));
            self::assertSame([], $row->takeOriginalPrimary());
        }
    }

    public function testDefaultValueBatchAfterInsertKeyMutationRejectsAndRestoresAllRows(): void
    {
        $pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec('CREATE TABLE generated_only (id INTEGER PRIMARY KEY AUTOINCREMENT)');
        $gateway = new EntityGateway(new PdoConnection($pdo));
        Session::use($gateway);
        $first = new GeneratedOnlyHookRow();
        $second = new GeneratedOnlyHookRow();
        $second->mutateIdAfterInsert = true;

        try {
            GeneratedOnlyHookRow::insertAll([$first, $second]);
            self::fail('A batch after-hook cannot publish a mutated generated key');
        } catch (\Pixiaoka\Orm\Exception\IdentityException $e) {
            self::assertStringContainsString('primary key', $e->getMessage());
        }

        self::assertSame(0, (int) $pdo->query('SELECT COUNT(*) FROM generated_only')->fetchColumn());
        foreach ([$first, $second] as $row) {
            self::assertTrue($row->isNew());
            self::assertFalse($row->propSet('id'));
            self::assertSame([], $row->takeOriginalPrimary());
        }
    }

    public function testNestedDefaultValueBatchFailureRestoresSavepointButAllowsOuterRetry(): void
    {
        $pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec('CREATE TABLE generated_only (id INTEGER PRIMARY KEY AUTOINCREMENT)');
        $gateway = new EntityGateway(new PdoConnection($pdo));
        Session::use($gateway);
        $failed = new GeneratedOnlyHookRow();
        $failed->failAfterInsert = true;
        $retry = new GeneratedOnlyHookRow();

        GeneratedOnlyHookRow::transaction(static function () use ($failed, $retry): void {
            try {
                GeneratedOnlyHookRow::transaction(static function () use ($failed): void {
                    GeneratedOnlyHookRow::insertAll([$failed]);
                });
                self::fail('The inner batch must fail after publishing its generated key');
            } catch (\RuntimeException $e) {
                self::assertSame('injected after-insert failure', $e->getMessage());
            }
            self::assertTrue($failed->isNew());
            self::assertFalse($failed->propSet('id'));
            GeneratedOnlyHookRow::insertAll([$retry]);
            self::assertFalse($retry->isNew());
        });

        self::assertSame(1, (int) $pdo->query('SELECT COUNT(*) FROM generated_only')->fetchColumn());
        self::assertGreaterThan(0, $retry->id);
        self::assertSame([[$retry->id]], $pdo->query('SELECT id FROM generated_only')->fetchAll(PDO::FETCH_NUM));
    }

    /** @return array<string, array{string}> */
    public static function liveDrivers(): array
    {
        return ['mysql' => ['mysql'], 'pgsql' => ['pgsql'], 'sqlite' => ['sqlite']];
    }

    private function connection(string $driver): PDO
    {
        if ($driver === 'sqlite') {
            return new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        }
        $prefix = 'PIXIAOKA_ORM_LIVE_' . strtoupper($driver);
        $dsn = getenv($prefix . '_DSN');
        if ($dsn === false || $dsn === '') {
            self::markTestSkipped('未配置 ' . $prefix . '_DSN');
        }
        $user = getenv($prefix . '_USER');
        $password = getenv($prefix . '_PASSWORD');

        return new PDO($dsn, $user === false ? null : $user, $password === false ? null : $password, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_EMULATE_PREPARES => false,
        ]);
    }

}

final class GeneratedOnlyRow extends Entity
{
    public static string $liveTable = 'generated_only';

    #[Column, PrimaryKey(generated: true)]
    public int $id;

    public static function table(): string { return self::$liveTable; }
}

final class GeneratedOnlyOtherRow extends Entity
{
    #[Column, PrimaryKey(generated: true)]
    public int $id;

    public static function table(): string { return 'generated_only'; }
}

final class GeneratedOnlyHookRow extends Entity
{
    public bool $failBeforeInsert = false;
    public bool $failAfterInsert = false;
    public bool $mutateIdAfterInsert = false;
    public int $afterInserts = 0;

    #[Column, PrimaryKey(generated: true)]
    public int $id;

    public static function table(): string { return 'generated_only'; }

    public function beforeInsert(): void
    {
        if ($this->failBeforeInsert) {
            throw new \RuntimeException('injected before-insert failure');
        }
    }

    public function afterInsert(): void
    {
        $this->afterInserts++;
        if ($this->mutateIdAfterInsert) {
            $this->id = 999;
        }
        if ($this->failAfterInsert) {
            throw new \RuntimeException('injected after-insert failure');
        }
    }
}

final class GeneratedOnlyDialectConnection implements Connection, DriverAwareConnection
{
    /** @var list<string> */
    public array $queries = [];
    /** @var list<string> */
    public array $executes = [];

    public function __construct(private readonly string $dialect) {}

    public function execute(string $sql, array $params): int
    {
        $this->executes[] = $sql;

        return 2;
    }

    public function queryOne(string $sql, array $params): ?array
    {
        $this->queries[] = $sql;

        return ['id' => 7];
    }

    public function queryAll(string $sql, array $params): array
    {
        $this->queries[] = $sql;

        return [['id' => 8], ['id' => 9]];
    }

    public function lastInsertId(): string { return '7'; }
    public function quoteIdentifier(string $identifier): string
    {
        $quote = $this->dialect === 'mysql' ? '`' : '"';
        return $quote . $identifier . $quote;
    }
    public function supportsReturning(): bool { return $this->dialect !== 'mysql'; }
    public function driver(): string { return $this->dialect; }
    public function beginTransaction(): bool { return true; }
    public function commit(): bool { return true; }
    public function rollback(): bool { return true; }
}
